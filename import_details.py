def make_detail(sections):
    """将section字典转为HTML"""
    html = ''
    icons = {
        '个性特征描述': '🧩',
        '可能存在的盲点': '⚠️',
        '工作中的优势': '💪',
        '工作中的劣势': '📉',
        '适合的岗位特质': '🎯',
        '适合的职业方向': '💼',
        '对组织的贡献': '🌟',
        '领导风格': '👑',
        '潜在缺陷': '🔴',
        '适合的工作环境': '🏢',
        '个人发展建议': '🌱',
    }
    for title, content in sections.items():
        icon = icons.get(title, '📌')
        html += f'<h3>{icon} {title}</h3>\n'
        if isinstance(content, list):
            html += '<ul>\n'
            for item in content:
                html += f'<li>{item}</li>\n'
            html += '</ul>\n'
        else:
            html += f'<p>{content}</p>\n'
    return html

